<?php

namespace Tests\Feature;

use App\Contracts\FbrGateway;
use App\Enums\FbrSubmissionStatus;
use App\Models\AuditLog;
use App\Models\CompanySetting;
use App\Models\FbrCompanyConfiguration;
use App\Models\PakistanFbrInvoice;
use App\Models\PakistanFbrInvoiceLine;
use App\Services\Fbr\FbrSubmissionResult;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

class FbrPortalSettingsTest extends TestCase
{
    use RefreshDatabase;

    public function test_portal_settings_are_company_scoped_versioned_and_resettable(): void
    {
        [$user, $company] = $this->actingAsCompanyUser(['portal.settings.view', 'portal.settings.manage']);
        $headers = ['X-Company-Id' => $company->id];
        $path = '/api/v1/pakistan-fbr/portal-settings';

        $this->getJson($path, $headers)->assertOk()->assertJsonPath('presentation.version', 1)
            ->assertJsonPath('fbr_configuration.credential_configured', false);
        $this->putJson($path, ['version' => 1, 'footer' => 'This document was generated by ZavSync',
            'declaration' => 'Computer-generated document', 'show_seller_phone' => false], $headers)
            ->assertOk()->assertJsonPath('presentation.version', 2)
            ->assertJsonPath('presentation.footer', 'This document was generated by ZavSync')
            ->assertJsonPath('presentation.show_seller_phone', false);
        $this->putJson($path, ['version' => 1, 'footer' => 'Stale overwrite'], $headers)
            ->assertConflict()->assertJsonPath('error_code', 'PORTAL_SETTINGS_VERSION_STALE');
        $this->postJson("$path/reset", ['version' => 2], $headers)->assertOk()
            ->assertJsonPath('presentation.version', 3)->assertJsonPath('presentation.footer', null)
            ->assertJsonPath('presentation.show_seller_phone', true);
        $this->assertDatabaseHas('audit_logs', ['company_id' => $company->id, 'action' => 'portal_settings_reset']);
    }

    public function test_portal_fbr_credential_reuses_encrypted_configuration_without_plaintext_response_or_audit(): void
    {
        [$user, $company] = $this->actingAsCompanyUser(['portal.settings.view', 'portal.settings.manage', 'fbr.configuration.manage']);
        $configuration = FbrCompanyConfiguration::factory()->for($company)->create(['credential' => null, 'updated_by' => $user->id]);
        $headers = ['X-Company-Id' => $company->id];
        $path = '/api/v1/pakistan-fbr/portal-settings/credential';
        $secret = 'highly-sensitive-test-token';

        $this->putJson($path, ['version' => 1, 'credential' => $secret], $headers)
            ->assertOk()->assertJsonPath('fbr_configuration.credential_configured', true)->assertDontSee($secret);
        $this->assertNotSame($secret, $configuration->fresh()->getRawOriginal('credential'));
        $this->assertSame($secret, $configuration->fresh()->credential);
        $this->assertStringNotContainsString($secret, AuditLog::query()->where('company_id', $company->id)->get()->toJson());
        $this->deleteJson($path, ['version' => 2], $headers)->assertOk()
            ->assertJsonPath('fbr_configuration.credential_configured', false);
        $this->assertNull($configuration->fresh()->credential);
    }

    public function test_accepted_invoice_print_freezes_portal_and_seller_values_without_fabricating_qr(): void
    {
        config()->set('services.fbr.pakistan_submission_enabled', true);
        config()->set('services.fbr.endpoints.sandbox', 'https://fbr.example.test/submit');
        $this->mock(FbrGateway::class)->shouldReceive('submit')->once()
            ->andReturn(new FbrSubmissionResult(FbrSubmissionStatus::Accepted, 'AUTHENTIC-REFERENCE', ['status' => 'accepted']));
        [$user, $company] = $this->actingAsCompanyUser(['portal.settings.view', 'portal.settings.manage', 'pakistan_fbr.view', 'pakistan_fbr.submit']);
        $settings = CompanySetting::factory()->for($company)->create(['legal_name' => 'Original Seller', 'email' => 'original@example.test']);
        FbrCompanyConfiguration::factory()->for($company)->create([
            'seller_business_name' => 'Original Seller', 'updated_by' => $user->id,
        ]);
        $headers = ['X-Company-Id' => $company->id];
        $this->putJson('/api/v1/pakistan-fbr/portal-settings', ['version' => 1, 'footer' => 'Original footer'], $headers)->assertOk();
        $invoice = PakistanFbrInvoice::factory()->for($company)->create(['created_by' => $user->id]);
        PakistanFbrInvoiceLine::factory()->for($invoice, 'invoice')->create();
        $path = "/api/v1/pakistan-fbr/invoices/{$invoice->id}/print-data";

        $this->getJson($path, $headers)->assertOk()->assertJsonPath('watermark', 'DRAFT / NOT SUBMITTED TO FBR')
            ->assertJsonPath('portal.footer', 'Original footer');
        $this->postJson("/api/v1/pakistan-fbr/invoices/{$invoice->id}/submit", [],
            ['X-Company-Id' => $company->id, 'Idempotency-Key' => 'print-snapshot-submit'])
            ->assertOk()->assertJsonPath('fbr_status', 'accepted');
        $this->getJson($path, $headers)->assertOk()->assertJsonPath('portal.footer', 'Original footer')
            ->assertJsonPath('verification.qr_content', null)
            ->assertJsonPath('verification.fbr_reference_number', 'AUTHENTIC-REFERENCE');
        $settings->update(['legal_name' => 'Changed Seller', 'email' => 'changed@example.test']);
        $this->putJson('/api/v1/pakistan-fbr/portal-settings', ['version' => 2, 'footer' => 'Changed footer'], $headers)->assertOk();
        $this->getJson($path, $headers)->assertOk()->assertJsonPath('portal.footer', 'Original footer')
            ->assertJsonPath('seller.business_name', 'Original Seller');
        $this->assertNotNull($invoice->fresh()->print_snapshot);
        $this->assertDatabaseCount('journals', 0);
    }

    public function test_historical_print_without_preserved_snapshot_never_borrows_current_company_presentation(): void
    {
        [$user, $company] = $this->actingAsCompanyUser(['pakistan_fbr.view']);
        CompanySetting::factory()->for($company)->create([
            'legal_name' => 'Unrelated Current Seller', 'fbr_document_footer' => 'Unrelated Current Footer',
        ]);
        FbrCompanyConfiguration::factory()->for($company)->create([
            'seller_business_name' => 'Unrelated Current FBR Seller', 'updated_by' => $user->id,
        ]);
        $invoice = PakistanFbrInvoice::factory()->for($company)->create([
            'created_by' => $user->id, 'is_historical' => true, 'document_state' => 'SUBMITTED',
            'fbr_status' => FbrSubmissionStatus::Accepted, 'seller_snapshot' => null, 'print_snapshot' => null,
        ]);

        $this->getJson("/api/v1/pakistan-fbr/invoices/{$invoice->id}", [
            'X-Company-Id' => $company->id,
        ])->assertOk()->assertJsonPath('buyer_verification.status', 'NOT_VERIFIED')
            ->assertJsonPath('buyer_verification.provider', null);
        $this->getJson("/api/v1/pakistan-fbr/invoices/{$invoice->id}/print-data", [
            'X-Company-Id' => $company->id,
        ])->assertOk()->assertJsonPath('snapshot_status', 'HISTORICAL_PRINT_SNAPSHOT_UNAVAILABLE')
            ->assertJsonPath('seller', null)->assertJsonPath('portal', null)
            ->assertDontSee('Unrelated Current Seller')->assertDontSee('Unrelated Current Footer');
    }

    public function test_issued_print_without_snapshot_does_not_borrow_later_company_presentation(): void
    {
        [$user, $company] = $this->actingAsCompanyUser(['pakistan_fbr.view']);
        CompanySetting::factory()->for($company)->create([
            'legal_name' => 'Later Seller', 'fbr_document_footer' => 'Later Footer',
        ]);
        $invoice = PakistanFbrInvoice::factory()->for($company)->create([
            'created_by' => $user->id, 'is_historical' => false, 'document_state' => 'ISSUED',
            'fbr_status' => FbrSubmissionStatus::Accepted, 'seller_snapshot' => null, 'print_snapshot' => null,
        ]);

        $this->getJson("/api/v1/pakistan-fbr/invoices/{$invoice->id}/print-data", [
            'X-Company-Id' => $company->id,
        ])->assertOk()->assertJsonPath('snapshot_status', 'PREVIOUSLY_ISSUED_SNAPSHOT_UNAVAILABLE')
            ->assertJsonPath('seller', null)->assertJsonPath('portal', null)
            ->assertDontSee('Later Seller')->assertDontSee('Later Footer');
    }
}
